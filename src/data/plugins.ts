/** 插件来源：核心 / 内置 / 外部，与客户端 PluginSource 保持一致 */
export type PluginSource = "core" | "builtin" | "external";

export interface CatalogPlugin {
  /** 插件包名，与 plugin.json 的 name 一致 */
  id: string;
  icon: PluginIcon;
  category: PluginCategory;
  source: PluginSource;
  /** 未知版本用 null，展示为「最新版」 */
  version: string | null;
  minAppVersion: string | null;
  permissions: string[];
  docsSlug: string;
  name: Record<PluginLang, string>;
  desc: Record<PluginLang, string>;
}

